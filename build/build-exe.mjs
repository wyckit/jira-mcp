// Builds a single self-contained Windows .exe using Node's Single Executable
// Application support. The result needs no Node, no npm, and no install on the
// target machine — copy the file and run it.
//
//   node build/build-exe.mjs
//
// Requires npm only on the BUILD machine (for postject, the official injector).
// The produced .exe has no such requirement.
//
// Because the server is dependency-free, "bundling" is just concatenating four
// source files and stripping their ESM import/export syntax — no bundler needed.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, statSync } from "fs";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const buildDir = join(root, "build");
const distDir = join(root, "dist");
mkdirSync(buildDir, { recursive: true });
mkdirSync(distDir, { recursive: true });

const read = (p) => readFileSync(join(root, p), "utf8");
const stripExports = (src) => src.replace(/^export (?=(const|function|class|let|var)\b)/gm, "");

// --- assemble a single CommonJS file -------------------------------------
// SEA runs CommonJS, so ESM syntax has to go. The exe always uses the bundled
// dependency-free runtime, so lib/runtime.mjs (dynamic imports + top-level
// await) is deliberately excluded.

const zod = stripExports(read("lib/zod-lite.mjs"));

const mcp = stripExports(read("lib/mcp-lite.mjs")).replace(
  /^import\s*\{[^}]*\}\s*from\s*["']\.\/zod-lite\.mjs["'];?\s*$/gm,
  ""
);

let server = read("server.js")
  .replace(/^#!.*\n/, "")
  .replace(
    /^import\s*\{[^}]*\}\s*from\s*["']\.\/lib\/runtime\.mjs["'];?\s*$/gm,
    'const runtime = "lite";'
  )
  // Top-level await is not valid in CommonJS. connect() only installs stdin
  // listeners and returns, so dropping the await is behaviourally identical.
  .replace(/^await server\.connect\(transport\);$/gm, "server.connect(transport);")
  // Named imports of Node builtins become require destructuring.
  .replace(
    /^import\s*\{([^}]*)\}\s*from\s*["'](node:[a-z_]+)["'];?\s*$/gm,
    (_, names, mod) => `const {${names.trim()} } = require("${mod}");`
  );

for (const [label, src, needle] of [
  ["runtime import", server, 'const runtime = "lite";'],
  ["zod exports", zod, "const z = {"],
  ["mcp exports", mcp, "class McpServer {"],
]) {
  if (!src.includes(needle)) throw new Error(`Bundle transform failed: ${label} (expected ${needle})`);
}
if (server.includes("await server.connect")) throw new Error("Bundle transform failed: top-level await remains");
if (/^\s*(import|export)\s/m.test(zod + mcp + server)) {
  throw new Error("Bundle transform failed: ESM syntax remains in bundle");
}
// import.meta is a syntax error in CommonJS and would only surface at runtime
// inside the compiled binary, where it is far more expensive to diagnose.
if (/import\.meta/.test(zod + mcp + server)) {
  throw new Error("Bundle transform failed: import.meta is not available in CommonJS — use process.argv[1]/execPath");
}
if (!server.includes('require("node:fs")')) {
  throw new Error("Bundle transform failed: node builtin imports were not converted to require");
}

const bundle = [
  "// Generated by build/build-exe.mjs — do not edit.",
  "'use strict';",
  zod,
  mcp,
  server,
].join("\n");

const bundlePath = join(buildDir, "bundle.cjs");
writeFileSync(bundlePath, bundle);
console.log(`bundle:  ${bundlePath}  (${(bundle.length / 1024).toFixed(0)} KB)`);

// Fail early if the bundle isn't valid CommonJS.
execFileSync(process.execPath, ["--check", bundlePath], { stdio: "pipe" });
console.log("syntax:  ok");

// --- SEA blob -------------------------------------------------------------

const seaConfig = join(buildDir, "sea-config.json");
writeFileSync(
  seaConfig,
  JSON.stringify(
    {
      main: bundlePath.replace(/\\/g, "/"),
      output: join(buildDir, "sea-prep.blob").replace(/\\/g, "/"),
      disableExperimentalSEAWarning: true,
    },
    null,
    2
  )
);

execFileSync(process.execPath, ["--experimental-sea-config", seaConfig], { stdio: "inherit" });
console.log("blob:    ok");

// --- copy the node binary and inject the blob -----------------------------

const exeName = process.platform === "win32" ? "jira-mcp.exe" : "jira-mcp";
const exePath = join(distDir, exeName);
copyFileSync(process.execPath, exePath);

const FUSE = "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2";
const npx = process.platform === "win32" ? "npx.cmd" : "npx";
execFileSync(
  npx,
  ["--yes", "postject", exePath, "NODE_SEA_BLOB", join(buildDir, "sea-prep.blob"), "--sentinel-fuse", FUSE],
  { stdio: "inherit", shell: process.platform === "win32" }
);

const mb = (statSync(exePath).size / 1024 / 1024).toFixed(0);
console.log(`\nbuilt:   ${exePath}  (${mb} MB)`);
console.log("\nRun it with JIRA_BASE_URL and JIRA_PAT set; it speaks MCP over stdio.");
